/*
 ## Задание 3

 Пользователь вводит возраст. Используя switch, нужно определить категорию:
 ребенок, подросток, взрослый или пенсионер.
 */

print("Введите возраст:")
let ageInput = readLine() ?? ""

if let age = Int(ageInput), age >= 0 {
    switch age {
    case 0...12:
        print("Ребенок")
    case 13...17:
        print("Подросток")
    case 18...64:
        print("Взрослый")
    case 65...:
        print("Пенсионер")
    default:
        print("Ошибка: некорректное значение возраста")
    }
} else {
    print("Ошибка: некорректное значение возраста")
}
